"""Builds gem facet planes for analytic ray tracing in shaders/gem.fp.

For each geometry/gems/*.buffer:
  1. convex hull of the vertices (the meshes are slightly non-convex and noisy after export);
  2. nearly coplanar hull triangles are merged into facets;
  3. each plane is shifted so that it remains a supporting plane (all vertices inside);
  4. if there are more facets than MAX_PLANES, the merge tolerance grows until they fit.

Output: geometry/gems/planes.lua, plane = {nx, ny, nz, w}, point x is inside
if dot(n, x) <= w for all planes. Coordinates are local, as in .buffer.

Run from the project root:  python tools/extract_gem_planes.py
Requires numpy and scipy. MAX_PLANES must match GEM_MAX_PLANES in shaders/gem.fp.
"""

import json
import math
from pathlib import Path

import numpy as np
from scipy.spatial import ConvexHull

ROOT = Path(__file__).resolve().parents[1]
GEMS_DIR = ROOT / "geometry" / "gems"
OUTPUT_PATH = GEMS_DIR / "planes.lua"
MAX_PLANES = 96


def load_positions(path):
    streams = json.loads(path.read_text("utf-8"))
    data = next(s for s in streams if s["name"] == "position")["data"]
    return np.asarray(data, dtype=np.float64).reshape(-1, 3)


def hull_triangles(vertices):
    hull = ConvexHull(vertices)
    tris = []
    for simplex, eq in zip(hull.simplices, hull.equations):
        a, b, c = vertices[simplex]
        area = 0.5 * np.linalg.norm(np.cross(b - a, c - a))
        if area < 1e-12:
            continue
        tris.append((eq[:3] / np.linalg.norm(eq[:3]), area))
    return tris


def merge_planes(tris, vertices, angle_deg, dist_tol):
    cos_tol = math.cos(math.radians(angle_deg))
    groups = []  # [normal_sum, area, w]
    for normal, area in sorted(tris, key=lambda t: -t[1]):
        w = float(np.max(vertices @ normal))
        for g in groups:
            gn = g[0] / np.linalg.norm(g[0])
            if float(gn @ normal) >= cos_tol and abs(g[2] - w) <= dist_tol:
                g[0] = g[0] + normal * area
                g[1] += area
                g[2] = float(np.max(vertices @ (g[0] / np.linalg.norm(g[0]))))
                break
        else:
            groups.append([normal * area, area, w])

    planes = []
    for normal_sum, _area, _w in groups:
        n = normal_sum / np.linalg.norm(normal_sum)
        planes.append((n, float(np.max(vertices @ n))))
    return planes


def build_planes(vertices):
    tris = hull_triangles(vertices)
    radius = float(np.max(np.linalg.norm(vertices, axis=1)))
    angle, dist = 1.0, radius * 0.01
    while True:
        planes = merge_planes(tris, vertices, angle, dist)
        if len(planes) <= MAX_PLANES:
            return planes, angle
        angle *= 1.25
        dist *= 1.25


def main():
    out = [
        "-- Generated by tools/extract_gem_planes.py, do not edit by hand.",
        "-- Facet planes (convex hull) in local coordinates: {nx, ny, nz, w}.",
        "return {",
    ]
    for path in sorted(GEMS_DIR.glob("*.buffer")):
        vertices = load_positions(path)
        planes, angle = build_planes(vertices)
        print(f"{path.stem:40s} planes={len(planes):3d} merge_angle={angle:.2f}deg")
        out.append(f'  ["{path.stem}"] = {{')
        for n, w in planes:
            out.append(f"    {{{n[0]:.6f}, {n[1]:.6f}, {n[2]:.6f}, {w:.6f}}},")
        out.append("  },")
    out.append("}")
    OUTPUT_PATH.write_text("\n".join(out) + "\n", "utf-8")
    print(f"written {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
